-- Narudžbe: šema baze (PostgreSQL)
-- Pet tabela: kupci i proizvodi (s kategorijama), narudžbe i njihove stavke.
-- Jedna narudžba ima više stavki; jedna stavka je jedan proizvod u jednoj narudžbi.

create table kupci (
  id      integer generated by default as identity primary key,
  sifra   varchar(12)  not null unique,
  naziv   varchar(100) not null,
  vrsta   varchar(20)  not null
          check (vrsta in ('KAFIC', 'RESTORAN', 'PRODAVNICA', 'HOTEL', 'KANCELARIJA')),
  grad    varchar(60)  not null,
  email   varchar(120),
  kreiran date         not null
);

create table kategorije (
  id    integer generated by default as identity primary key,
  naziv varchar(60) not null unique
);

create table proizvodi (
  id             integer generated by default as identity primary key,
  sifra          varchar(15)   not null unique,
  naziv          varchar(100)  not null,
  kategorija_id  integer       not null references kategorije (id),
  jedinica_mjere varchar(10)   not null,
  cijena         numeric(12,2) not null check (cijena >= 0), -- trenutna cijena iz cjenovnika
  aktivan        boolean       not null default true
);

create table narudzbe (
  id             integer generated by default as identity primary key,
  broj           varchar(20)  not null unique,
  kupac_id       integer      not null references kupci (id),
  datum          date         not null,
  datum_isporuke date,
  status         varchar(20)  not null default 'KREIRANA'
                 check (status in ('KREIRANA', 'U_OBRADI', 'POSLATA', 'ISPORUCENA', 'OTKAZANA')),
  napomena       varchar(255),
  kreirana       timestamptz  not null default now()
);

create table stavke_narudzbe (
  id               integer generated by default as identity primary key,
  narudzba_id      integer       not null references narudzbe (id) on delete cascade,
  proizvod_id      integer       not null references proizvodi (id),
  kolicina         integer       not null check (kolicina > 0),
  cijena_po_komadu numeric(12,2) not null check (cijena_po_komadu >= 0), -- cijena u trenutku narudžbe
  rabat_posto      numeric(5,2)  not null default 0 check (rabat_posto between 0 and 100),
  unique (narudzba_id, proizvod_id)
);

create index on narudzbe (kupac_id);
create index on narudzbe (datum);
create index on stavke_narudzbe (proizvod_id);
